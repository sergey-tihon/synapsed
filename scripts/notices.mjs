// Regenerates THIRD-PARTY-NOTICES.txt from the root Cargo.lock and package-lock.json.
//
// `generate` covers every locked platform: Rust sources come from `cargo metadata`
// (which downloads missing crates), and npm packages not installed for this host are
// read from their locked registry tarballs. `check` is offline and only verifies that
// the catalogue lists exactly the locked third-party name/version pairs.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = join(root, "THIRD-PARTY-NOTICES.txt");
const licenseFile = /^(licen[cs]e|copying|copyright|notice|unlicense)([-._].*)?$/i;

const header = `Synapsed third-party notices
============================

Project source is MIT OR Apache-2.0. Third-party components retain their own
licenses. Versions are locked in Cargo.lock and package-lock.json. This catalog
includes resolved build/platform dependencies as well as redistributed runtime
components; inclusion does not imply every dependency ships in every artifact.
Generated by \`node scripts/notices.mjs generate\`; do not edit by hand.
`;

function lockedCrates(source) {
  const crates = [];
  for (const block of source.split(/^\[\[package\]\]$/m).slice(1)) {
    const name = block.match(/^name = "([^"]+)"$/m)?.[1];
    const version = block.match(/^version = "([^"]+)"$/m)?.[1];
    // Workspace members have no source; everything else is third-party.
    if (name && version && /^source = /m.test(block)) crates.push({ name, version });
  }
  return crates;
}

function lockedPackages(lock) {
  return Object.entries(lock.packages)
    .filter(([path, entry]) => path.includes("node_modules/") && !entry.link)
    .map(([path, entry]) => ({
      path,
      name: entry.name ?? path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length),
      version: entry.version,
      license: entry.license,
      resolved: entry.resolved,
      integrity: entry.integrity,
      dev: entry.dev === true,
    }));
}

const key = (ecosystem, name, version) => `${ecosystem} ${name} ${version}`;

async function expectedKeys() {
  const crates = lockedCrates(await readFile(join(root, "Cargo.lock"), "utf8"));
  const packages = lockedPackages(JSON.parse(await readFile(join(root, "package-lock.json"), "utf8")));
  return [
    ...crates.map(({ name, version }) => key("Rust", name, version)),
    ...packages.map(({ name, version }) => key("JavaScript", name, version)),
  ];
}

function listedKeys(text) {
  return [...text.matchAll(/^(Rust|JavaScript)(?: development)? dependency: (\S+) (\S+)$/gm)].map(
    ([, ecosystem, name, version]) => key(ecosystem, name, version),
  );
}

async function licenseTexts(directory) {
  if (!existsSync(directory)) return [];
  const names = (await readdir(directory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && licenseFile.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  return Promise.all(
    names.map(async (name) => ({ name, text: (await readFile(join(directory, name), "utf8")).trimEnd() })),
  );
}

function spdxFallback(declaration) {
  const ids = [...new Set((declaration ?? "").match(/[A-Za-z0-9.+-]+/g) ?? [])].filter(
    (id) => !["AND", "OR", "WITH"].includes(id),
  );
  return ids.map((id) => `License text: https://spdx.org/licenses/${id}.html`);
}

function entry(title, declaration, upstream, texts) {
  const lines = [title, `License declaration: ${declaration ?? "UNKNOWN"}`, `Upstream: ${upstream}`];
  if (texts.length) for (const { name, text } of texts) lines.push("", `--- ${name} ---`, text);
  else lines.push(...spdxFallback(declaration));
  return `${lines.join("\n")}\n`;
}

async function rustEntries() {
  const metadata = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked", "--all-features"], {
      cwd: root,
      maxBuffer: 256 * 1024 * 1024,
      encoding: "utf8",
    }),
  );
  const packages = metadata.packages
    .filter((pkg) => pkg.source !== null)
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
  return Promise.all(
    packages.map(async (pkg) =>
      entry(
        `Rust dependency: ${pkg.name} ${pkg.version}`,
        pkg.license ?? (pkg.license_file ? `See ${pkg.license_file}` : undefined),
        pkg.repository ?? pkg.homepage ?? `https://crates.io/crates/${pkg.name}`,
        await licenseTexts(dirname(pkg.manifest_path)),
      ),
    ),
  );
}

async function installedDirectory(pkg) {
  const directory = join(root, pkg.path);
  try {
    const manifest = JSON.parse(await readFile(join(directory, "package.json"), "utf8"));
    if (manifest.version === pkg.version) return { directory, manifest };
  } catch {
    // Not installed for this host (e.g. another platform's optional binary).
  }
  return undefined;
}

async function extractedDirectory(pkg, cache) {
  if (!pkg.resolved) throw new Error(`No locked tarball for ${pkg.name}@${pkg.version}`);
  const target = join(cache, createHash("sha256").update(pkg.resolved).digest("hex"));
  if (!existsSync(join(target, "package"))) {
    const response = await fetch(pkg.resolved);
    if (!response.ok) throw new Error(`Cannot download ${pkg.resolved}: ${response.status}`);
    const body = Buffer.from(await response.arrayBuffer());
    if (pkg.integrity) {
      const [algorithm, digest] = pkg.integrity.split("-", 2);
      if (createHash(algorithm).update(body).digest("base64") !== digest)
        throw new Error(`Integrity mismatch for ${pkg.name}@${pkg.version}`);
    }
    await mkdir(target, { recursive: true });
    const archive = join(target, "package.tgz");
    await writeFile(archive, body);
    execFileSync("tar", ["-xzf", archive, "-C", target]);
  }
  // npm tarballs normally use `package/`, but a few use another top-level folder.
  const [top] = (await readdir(target, { withFileTypes: true })).filter((item) => item.isDirectory());
  const directory = join(target, top.name);
  return { directory, manifest: JSON.parse(await readFile(join(directory, "package.json"), "utf8")) };
}

async function javascriptEntries(cache) {
  const packages = lockedPackages(JSON.parse(await readFile(join(root, "package-lock.json"), "utf8")));
  const entries = [];
  for (const pkg of packages) {
    const { directory, manifest } = (await installedDirectory(pkg)) ?? (await extractedDirectory(pkg, cache));
    const declared =
      pkg.license ??
      (typeof manifest.license === "string" ? manifest.license : manifest.license?.type) ??
      manifest.licenses?.map((item) => item.type ?? item).join(" OR ");
    entries.push(
      entry(
        `JavaScript${pkg.dev ? " development" : ""} dependency: ${pkg.name} ${pkg.version}`,
        declared,
        `https://www.npmjs.com/package/${pkg.name}`,
        await licenseTexts(directory),
      ),
    );
  }
  return entries;
}

async function check() {
  const expected = await expectedKeys();
  const listed = listedKeys(await readFile(output, "utf8"));
  const listedSet = new Set(listed);
  const expectedSet = new Set(expected);
  const missing = [...expectedSet].filter((item) => !listedSet.has(item));
  const extra = [...listedSet].filter((item) => !expectedSet.has(item));
  if (missing.length || extra.length) {
    throw new Error(
      [
        "THIRD-PARTY-NOTICES.txt is out of sync with the lockfiles; run `npm run notices`.",
        ...missing.map((item) => `  missing: ${item}`),
        ...extra.map((item) => `  stale:   ${item}`),
      ].join("\n"),
    );
  }
}

async function generate() {
  const cache = await mkdtemp(join(tmpdir(), "synapsed-notices-"));
  try {
    const sections = [header, ...(await rustEntries()), ...(await javascriptEntries(cache))];
    await writeFile(output, `${sections.join("\n")}`);
  } finally {
    await rm(cache, { recursive: true, force: true });
  }
  await check();
}

const mode = process.argv[2];
if (mode === "generate") await generate();
else if (mode === "check") await check();
else throw new Error("Usage: node scripts/notices.mjs generate|check");
