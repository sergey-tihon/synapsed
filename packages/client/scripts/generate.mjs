import { mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";
import ts from "typescript";

const packageDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const banner = "// Generated by npm run api:generate. Do not edit.\n";
const draft07 = "http://json-schema.org/draft-07/schema#";

// Stable object-key ordering also fixes Ajv's generated function allocation order.
function canonicalize(value) {
  if (Array.isArray(value)) return value.map(canonicalize);
  if (value !== null && typeof value === "object") {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, canonicalize(value[key])]),
    );
  }
  return value;
}

function requireSelfContained(value, root) {
  if (Array.isArray(value)) {
    for (const item of value) requireSelfContained(item, root);
  } else if (value !== null && typeof value === "object") {
    if (typeof value.$ref === "string" && !value.$ref.startsWith("#")) {
      throw new Error(`${root} contains an external schema reference.`);
    }
    for (const child of Object.values(value)) requireSelfContained(child, root);
  }
}

function exportedTypeNames(source, root) {
  const file = ts.createSourceFile(`${root}.ts`, source, ts.ScriptTarget.ES2022, true);
  const names = file.statements.flatMap((statement) => {
    const isType = ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement);
    const exported = statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword);
    return isType && exported ? [statement.name.text] : [];
  });
  if (!names.includes(root)) throw new Error(`Type generation did not declare ${root}.`);
  return names;
}

function generateGuards(roots) {
  return `${banner}${roots.map((root) => `import type { ${root} } from "./${root}.js";`).join("\n")}
import { ${roots.map((root) => `check${root}`).join(", ")} } from "./standalone.js";

export type ApiSchemaName = ${roots.map((root) => JSON.stringify(root)).join(" | ")};

// Do not expose Ajv's errors, paths, parameters, or the rejected payload.
export class ProtocolValidationError extends Error {
  readonly schema: ApiSchemaName;

  constructor(schema: ApiSchemaName) {
    super(\`Invalid Synapsed \${schema} data.\`);
    this.name = "ProtocolValidationError";
    this.schema = schema;
  }
}
${roots
  .map(
    (root) => `
export function is${root}(value: unknown): value is ${root} {
  const valid = check${root}(value);
  check${root}.errors = null;
  return valid;
}

export function validate${root}(value: unknown): ${root} {
  if (!is${root}(value)) throw new ProtocolValidationError("${root}");
  return value;
}
`,
  )
  .join("")}`;
}

export async function generate(inputDirectory, outputDirectory) {
  const input = path.resolve(inputDirectory);
  const output = path.resolve(outputDirectory);
  const parsedRoots = JSON.parse(await readFile(path.join(input, "roots.json"), "utf8"));
  if (!Array.isArray(parsedRoots) || parsedRoots.some((root) => typeof root !== "string")) {
    throw new Error("Schema roots manifest must be an array of names.");
  }
  const roots = Object.freeze(parsedRoots);
  if (input === output || output.startsWith(`${input}${path.sep}`)) {
    throw new Error("Generated output must be separate from the schema directory.");
  }
  const expectedSchemas = roots.map((root) => `${root}.json`).sort();
  const schemaEntries = await readdir(input, { withFileTypes: true });
  const actualSchemas = schemaEntries
    .filter((entry) => entry.name !== "roots.json")
    .map((entry) => entry.name)
    .sort();
  if (
    schemaEntries.some((entry) => !entry.isFile()) ||
    JSON.stringify(actualSchemas) !== JSON.stringify(expectedSchemas)
  ) {
    throw new Error(`Schema directory must contain exactly: ${expectedSchemas.join(", ")}.`);
  }

  const ajv = new Ajv({
    strict: true,
    strictNumbers: true,
    allErrors: false,
    coerceTypes: false,
    useDefaults: false,
    removeAdditional: false,
    verbose: false,
    messages: false,
    validateFormats: true,
    code: { source: true, esm: true, lines: true },
  });
  addFormats(ajv, { mode: "full", formats: ["uuid", "date-time"], keywords: false });

  const files = new Map();
  const declarations = new Map();
  const validatorExports = {};
  for (const root of roots) {
    const schema = canonicalize(JSON.parse(await readFile(path.join(input, `${root}.json`), "utf8")));
    if (schema.$schema !== draft07) throw new Error(`${root} must declare JSON Schema draft07.`);
    requireSelfContained(schema, root);
    const key = `https://synapsed.local/schema/${root}.json`;
    ajv.addSchema(schema, key);
    ajv.getSchema(key);
    validatorExports[`check${root}`] = key;
    const source = await compile({ ...schema, title: root }, root, {
      bannerComment: banner.trimEnd(),
      cwd: input,
      $refOptions: { resolve: { file: false, http: false } },
      additionalProperties: true,
      enableConstEnums: false,
      inferStringEnumKeysFromValues: false,
      strictIndexSignatures: true,
      unknownAny: true,
      ignoreMinAndMaxItems: true,
      format: true,
      style: { singleQuote: false, semi: true, tabWidth: 2, printWidth: 120 },
    });
    files.set(`${root}.ts`, source.endsWith("\n") ? source : `${source}\n`);
    declarations.set(root, exportedTypeNames(source, root));
  }

  files.set("standalone.js", `${banner}${standaloneCode(ajv, validatorExports)}\n`);
  files.set(
    "standalone.d.ts",
    `${banner}type StandaloneValidator = {
  (value: unknown): boolean;
  errors?: readonly unknown[] | null;
};
${roots.map((root) => `export declare const check${root}: StandaloneValidator;`).join("\n")}
`,
  );
  files.set("guards.ts", generateGuards(roots));

  // Each root remains self-contained. Export each shared nested DTO once, while
  // giving the eight public roots precedence over another root's nested copy.
  const exports = new Map(roots.map((root) => [root, root]));
  for (const root of roots) {
    for (const name of declarations.get(root)) {
      if (!exports.has(name)) exports.set(name, root);
    }
  }
  files.set(
    "index.ts",
    `${banner}${Array.from(exports)
      .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
      .map(([name, root]) => `export type { ${name} } from "./${root}.js";`)
      .join("\n")}
export * from "./guards.js";
`,
  );

  // Compute everything before touching included output; remove obsolete generated
  // files so regeneration and api:check compare the complete file set, not a subset.
  await mkdir(output, { recursive: true });
  for (const entry of await readdir(output, { withFileTypes: true })) {
    if (!entry.isFile()) throw new Error("Generated directory must contain files only.");
  }
  for (const entry of await readdir(output)) {
    if (!files.has(entry)) await rm(path.join(output, entry));
  }
  for (const [name, contents] of files) {
    await writeFile(path.join(output, name), contents, "utf8");
  }
}

const isMain = process.argv[1] !== undefined && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const args = process.argv.slice(2);
  if (args.length !== 0 && args.length !== 2) {
    throw new Error("Usage: node scripts/generate.mjs [INPUT_SCHEMA_DIR OUTPUT_GENERATED_DIR]");
  }
  await generate(
    args[0] ?? path.join(packageDirectory, "schema"),
    args[1] ?? path.join(packageDirectory, "src/generated"),
  );
}
